import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const cli = join(root, "dist", "index.js");
const temporary = mkdtempSync(join(tmpdir(), "pjan-126-gitignore-"));
const supportedRoots = [".claude", ".codex", ".gemini", ".copilot", ".opencode", ".kimi-code"];

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, encoding: "utf8" });
  assert.equal(result.status, 0, `${command} ${args.join(" ")} failed\n${result.stdout}\n${result.stderr}`);
  return result;
}

function runJson(args) {
  const result = spawnSync(process.execPath, [cli, ...args], { cwd: root, encoding: "utf8" });
  assert.ok(result.stdout.trim(), `${args.join(" ")} produced no JSON\n${result.stderr}`);
  return JSON.parse(result.stdout);
}

try {
  const copier = readFileSync(join(root, "templates", "commonproject", "copier.yml"), "utf8");
  assert.doesNotMatch(copier, /cp ~\/\.config\/git\/ignore/, "CommonProject must never copy a machine-global ignore into a repo");
  assert.doesNotMatch(copier, /!\.claude\//, "CommonProject must not override the global client-root policy");
  assert.match(copier, /CommonProject repository contract/, "CommonProject should name its small repo-owned contract");

  const repo = join(temporary, "legacy-repo");
  mkdirSync(join(repo, ".agents", "skills", "example"), { recursive: true });
  mkdirSync(join(repo, ".claude"), { recursive: true });
  writeFileSync(join(repo, ".agents", "skills", "example", "SKILL.md"), "---\nname: example\n---\n");
  writeFileSync(join(repo, ".claude", "settings.json"), "{\"keep\":true}\n");
  writeFileSync(
    join(repo, ".gitignore"),
    [
      "custom-cache/",
      ".lastagent",
      "# Generated CLI configurations are durable project state...",
      ...supportedRoots.flatMap((clientRoot) => [`!${clientRoot}/`, `!${clientRoot}/**`]),
      "# ...but their skill projections are regenerated by `bmad-method install` and",
      "# `mise run skills:sync`, so they stay out of the tree. No trailing slash:",
      "# some CLIs get a real directory here and some get a symlink.",
      "/.agents/skills/",
      ...supportedRoots.map((clientRoot) => `${clientRoot}/skills/`),
      "",
    ].join("\n"),
  );

  run("git", ["init", "-q"], repo);
  run("git", ["add", "-f", ".gitignore", ".claude/settings.json"], repo);

  const migrated = runJson(["migrate", "bmad.cli-roots", repo, "--json"]);
  assert.equal(migrated.ok, true, JSON.stringify(migrated));
  assert.equal(migrated.results[0].status, "applied", JSON.stringify(migrated.results[0]));

  const next = readFileSync(join(repo, ".gitignore"), "utf8");
  assert.match(next, /^custom-cache\/$/m, "unowned project rules must survive");
  assert.match(next, /^\.lastagent$/m, "pjangler must not opportunistically remove unrelated global overlaps");
  assert.match(next, /^# Canonical agent config lives in \.agents; generated skill projections stay local\.$/m);
  assert.equal((next.match(/^\/\.agents\/skills$/gm) ?? []).length, 1, "the canonical projection rule should appear once");
  for (const clientRoot of supportedRoots) {
    assert.doesNotMatch(next, new RegExp(`^!${clientRoot.replace(".", "\\.")}\\/`, "m"), `${clientRoot} must not be unignored`);
    assert.doesNotMatch(next, new RegExp(`^${clientRoot.replace(".", "\\.")}\\/skills\\/?$`, "m"), `${clientRoot}/skills is global policy`);
  }

  const tracked = run("git", ["ls-files", "--", ".claude/settings.json"], repo).stdout.trim();
  assert.equal(tracked, ".claude/settings.json", "structural parity must never mutate an existing repo's Git index");

  const audit = runJson(["audit", repo, "--json"]);
  const finding = audit.rules.find((rule) => rule.id === "bmad.cli-roots");
  assert.equal(finding.status, "pass", JSON.stringify(finding));

  const rerun = runJson(["migrate", "bmad.cli-roots", repo, "--json"]);
  assert.equal(rerun.results[0].status, "noop", JSON.stringify(rerun.results[0]));

  console.log("PJAN-126 gitignore policy regressions: PASS");
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
